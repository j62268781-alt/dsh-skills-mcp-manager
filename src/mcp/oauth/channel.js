/**
 * 授权回调页与面板之间的同源广播频道名。
 *
 * ## 为什么需要它
 *
 * 授权在**另一个标签页**里完成（回调页），而面板不知道用户什么时候回来。它只能靠轮询：
 * 运行时状态每 5 秒拉一次。于是「回调完成 → 工具出现」中间有一段空白，用户看到的是
 * 卡片还在说「需要授权」，而其实什么都好了。
 *
 * 两个页面**同源**（同一个 webServer 的同一个 origin），所以可以用 `BroadcastChannel`
 * 直接通知：回调页说一声，面板立刻重新拉一次运行时状态。
 *
 * ## 为什么单独一个模块
 *
 * Host 侧（回调页）与浏览器侧（面板）都要用这个字符串，而它们**不能互相 import**：
 * 面板 bundle 引 Host 模块会把整条 Host 依赖链拖进浏览器。一个只有常量的模块是两边
 * 都能安全引用的最小交集 —— 也让「两边必须一致」这件事只有一个出处。
 *
 * 它是纯字符串，不是凭据：频道只在同源页面之间可见，消息内容也只是一个「刷一下」的信号。
 */

/** BroadcastChannel 名。改动它等于同时改两端，所以不要各写各的。 */
export const AUTH_CHANNEL = 'dsh-skills-mcp-manager/oauth'

/** 回调页发、面板收的信号。只有一个含义：授权流程刚刚走完了。 */
export const AUTH_DONE = 'authorized'
